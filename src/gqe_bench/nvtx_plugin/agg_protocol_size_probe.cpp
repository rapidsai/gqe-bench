#include "agg_protocol.hpp"

#include <cstddef>
#include <cstdio>

int main(int argc, char* argv[])
{
  if (argc != 2) {
    std::fprintf(stderr, "usage: %s <output.py>\n", argv[0]);
    return 1;
  }
  std::FILE* out = std::fopen(argv[1], "w");
  if (out == nullptr) {
    std::fprintf(stderr, "failed to open %s for writing\n", argv[1]);
    return 1;
  }
  std::fprintf(out,
               "# Auto-generated by CMake. Do not edit.\n"
               "#\n"
               "# Sizes and field offsets of the agg_protocol shm-segment layout,\n"
               "# computed from sizeof() and offsetof() of agg_protocol.hpp types.\n"
               "\n");
  std::fprintf(out, "K_HEADER_BYTES = %zu\n", sizeof(gqe_bench::agg_header));
  std::fprintf(out, "K_SLOT_BYTES = %zu\n", sizeof(gqe_bench::agg_slot));
  std::fprintf(out,
               "K_HEADER_REQUEST_OFFSET = %zu\n",
               offsetof(gqe_bench::agg_header, requested_experiment_id));
  std::fclose(out);
  return 0;
}
